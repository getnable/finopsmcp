#!/usr/bin/env python3
"""Write the environment variable reference in docs/HEADLESS.md from the code.

finops.env_vars.KNOWN is every FINOPS_* and NABLE_* name the package reads
(tests/test_headless_env.py holds it to the source), and finops.env_vars.DOC
says what each one does. This renders DOC, section by section, between the
two env-table markers in the doc, so the table cannot list a name the code
does not read or miss one it does.

    python scripts/headless_env_table.py            print the table
    python scripts/headless_env_table.py --write    rewrite it in docs/HEADLESS.md
    python scripts/headless_env_table.py --check    exit 1 when the doc is stale

Standard library only, plus finops.env_vars (itself stdlib only).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC_PATH = ROOT / "docs" / "HEADLESS.md"
START = ("<!-- env-table:start. Generated by scripts/headless_env_table.py from "
         "src/finops/env_vars.py; edit DOC there, then run it with --write. -->")
END = "<!-- env-table:end -->"


def render() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from finops import env_vars

    out = [START, ""]
    for key, title in env_vars.SECTIONS:
        rows = [(name, text) for name, (section, text) in env_vars.DOC.items()
                if section == key]
        if not rows:
            continue
        out += [f"#### {title}", "", "| Variable | What it does |", "|---|---|"]
        bar = "\\|"         # a literal | inside a table cell
        out += [f"| `{name}` | {text.replace('|', bar)} |" for name, text in rows]
        out.append("")
    out.append(END)
    return "\n".join(out)


def splice(doc: str, table: str) -> str:
    head, sep, rest = doc.partition(START)
    if not sep:
        raise SystemExit(f"{DOC_PATH}: no env-table start marker")
    _old, sep, tail = rest.partition(END)
    if not sep:
        raise SystemExit(f"{DOC_PATH}: no env-table end marker")
    return head + table + tail


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="rewrite the table in the doc")
    ap.add_argument("--check", action="store_true", help="exit 1 when the doc is stale")
    args = ap.parse_args()
    table = render()
    if not (args.write or args.check):
        print(table)
        return 0
    doc = DOC_PATH.read_text(encoding="utf-8")
    new = splice(doc, table)
    if args.check:
        if new != doc:
            print(f"{DOC_PATH} is stale: run python scripts/headless_env_table.py --write",
                  file=sys.stderr)
            return 1
        return 0
    DOC_PATH.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
